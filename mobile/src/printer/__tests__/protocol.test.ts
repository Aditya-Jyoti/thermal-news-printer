import type { ReceiptBitmap } from '../../device/contracts';
import { crc8, encodeBitmap, frame, toHex } from '../protocol';
import golden from './fixtures/golden.json';

const fromHex = (h: string) => Uint8Array.from(h.match(/../g) ?? [], (x) => parseInt(x, 16));

describe('protocol golden vectors (generated by the Python reference)', () => {
  it.each(golden.crc)('crc8 of $data', ({ data, crc }) => {
    expect(crc8(fromHex(data))).toBe(crc);
  });

  for (const [name, c] of Object.entries(golden.cases)) {
    const bitmap: ReceiptBitmap = { width: 384, height: c.height, pixels: fromHex(c.pixelsHex) };
    it(`encodeBitmap ${name} is byte-identical`, () => {
      expect(toHex(encodeBitmap(bitmap))).toBe(c.job);
    });
    it(`encodeBitmap ${name} with custom energy/feed`, () => {
      expect(toHex(encodeBitmap(bitmap, { energy: 0x1234, feed: 7 }))).toBe(c.jobCustom);
    });
  }

  it('frames a get-state command', () => {
    expect(toHex(frame(0xa3, [0]))).toBe('5178a3000100' + '00' + '00' + 'ff');
  });
});
